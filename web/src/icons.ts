export type IconName = keyof typeof ICONS;

/** 这个名字在不在图标表里（调用处要区分「图标名」与「现成的文字 / 表情」时用）。 */
export function isIconName(v: string): v is IconName {
  return Object.hasOwn(ICONS, v);
}

const NS = "http://www.w3.org/2000/svg";

/** 语义色类名：`ico-danger` / `ico-warn` / `ico-ok`，色值在 styles.css 里由 `--ico-tint` 定义。 */
function tintClass(tint: IconSpec["tint"]): string {
  return tint ? ` ico-${tint}` : "";
}

export interface IconOpts {
  /** 边长（px）。默认 16 —— 顶栏与工具行用它，行内小图标传 14。 */
  size?: number;
  /** 追加的类名（已有的 `ico` 与语义色类名不会丢）。 */
  cls?: string;
}

/** 一个图标节点。挂 DOM 用这个。 */
